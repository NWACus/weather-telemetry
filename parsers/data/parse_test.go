func TestInsertNewlines(t *testing.T) {
	for _, testCase := range []struct {
		name      string
		raw       []byte
		expected  []byte
		shouldErr bool
	}{
		{
			name: "nothing to do",
			raw: []byte(`460,2007,241,1700,0,12.82,12.89,0,78.24,25.43,7.718,0
460,2007,241,1800,0,12.88,12.92,0,77.51,24.88,3.533,0
460,2007,241,1900,0,12.83,12.86,0,76.44,24.44,3.463,0
460,2007,241,2000,0,12.73,12.78,0,72.64,23.64,1.152,0`),
			expected: []byte(`460,2007,241,1700,0,12.82,12.89,0,78.24,25.43,7.718,0
460,2007,241,1800,0,12.88,12.92,0,77.51,24.88,3.533,0
460,2007,241,1900,0,12.83,12.86,0,76.44,24.44,3.463,0
460,2007,241,2000,0,12.73,12.78,0,72.64,23.64,1.152,0`),
		},
		{
			name: "corrupt first row",
			raw: []byte(`460,20
460,2007,241,1800,0,12.88,12.92,0,77.51,24.88,3.533,0
460,2007,241,1900,0,12.83,12.86,0,76.44,24.44,3.463,0
460,2007,241,2000,0,12.73,12.78,0,72.64,23.64,1.152,0`),
			shouldErr: true,
		},
		{
			name: "add some newlines",
			raw: []byte(`460,2007,243,2200,0,12.62,12.64,0,49.58,10.18,0.003,0
460,2007,243,2300,0,12.57,12.6,0,49.85,9.96,0.003,0460,2007,244,0,0,12.55,12.57,0,49.5,9.92,0.003,0460,2007,244,100,0,12.52,12.55,0,48.55,9.47,0.003,0
460,2007,244,200,0,12.51,12.53,0,47.78,9.04,0.003,0`),
			expected: []byte(`460,2007,243,2200,0,12.62,12.64,0,49.58,10.18,0.003,0
460,2007,243,2300,0,12.57,12.6,0,49.85,9.96,0.003,0
460,2007,244,0,0,12.55,12.57,0,49.5,9.92,0.003,0
460,2007,244,100,0,12.52,12.55,0,48.55,9.47,0.003,0
460,2007,244,200,0,12.51,12.53,0,47.78,9.04,0.003,0`),
		},
		{
			name: "don't add newlines for repeated data",
			raw: []byte(`355,2010,355,2005,13.26,34.97,59.11,0,0.168,79.92
355,2010,355,2010,13.27,34.74,60.66,0,0.168,79.92`),
			expected: []byte(`355,2010,355,2005,13.26,34.97,59.11,0,0.168,79.92
355,2010,355,2010,13.27,34.74,60.66,0,0.168,79.92`),
		},
	} {
		t.Run(testCase.name, func(t *testing.T) {
			amended, err := insertNewlines(testCase.raw)
			if (err != nil) != testCase.shouldErr {
				t.Errorf("insertNewlines() error = %v, wantErr %v", err, testCase.shouldErr)
			}
			if testCase.shouldErr {
				return
			}
			if diff := cmp.Diff(string(testCase.expected), string(amended)); diff != "" {
				t.Errorf("insertNewlines() mismatch (-want +got):\n%s", diff)
			}
		})
	}
}

